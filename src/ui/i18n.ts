const CATALOGUES: Record<Language, Catalogue> = { en: EN, de: DE, hr: HR, zh: ZH };

let current: Language = 'en';

export const language = (): Language => current;

export function setLanguage(next: Language): void {
  current = next;
  document.documentElement.lang = next;
}

/**
 * The text for `key` in the current language, with `{placeholders}` filled in. Falls back to the
 * English, which by construction has every key, so a gap in a translation shows the English words
 * rather than an identifier.
 */
export function t(key: TextKey, params: Readonly<Partial<Record<string, string | number>>> = {}): string {
  const text = CATALOGUES[current][key] ?? EN[key];
  return text.replace(/\{(\w+)\}/g, (whole, name: string) => {
    // A placeholder with nothing to put in it is left as written, which shows up in a screenshot
    // far more usefully than an empty gap would.
    const value = params[name];
    return value === undefined ? whole : String(value);
  });
}

/** Which keys a language is still missing; empty for a finished one. Used by the tests. */
export function missingKeys(lang: Language): TextKey[] {
  return (Object.keys(EN) as TextKey[]).filter((key) => CATALOGUES[lang][key] === undefined);
}

/** The language to start in when nothing was saved: the browser's, when it is one we speak. */
export function preferredLanguage(tags: readonly string[]): Language {
  for (const tag of tags) {
    const base = tag.toLowerCase().split('-')[0];
    const known = LANGUAGES.find((l) => l.value === base);
    if (known) return known.value;
    // zh-Hans, zh-TW and the rest all land on the one Chinese catalogue.
    if (base === 'cmn') return 'zh';
  }
  return 'en';
}
